import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('../native/internal/web/assets/app.js',import.meta.url),'utf8');
let calls=0;
const context=vm.createContext({state:{readOnly:true},fetch:async()=>{calls++;return {ok:true,json:async()=>({sequence:1})}},outboxReplay:false});
for(const name of ['request','resumeOutbox']){const line=source.split('\n').find(line=>line.startsWith(`async function ${name}(`));assert.ok(line);vm.runInContext(line,context)}
await assert.rejects(vm.runInContext('request("/v1/messages",{text:"must not send"})',context),error=>error.message==='restored_state_read_only');
assert.equal(calls,0,'readonly POST must not reach fetch');
assert.deepEqual(JSON.stringify(await vm.runInContext('request("/v1/snapshot")',context)),JSON.stringify({sequence:1}));
assert.equal(calls,1,'readonly GET is available');
await vm.runInContext('resumeOutbox()',context);assert.equal(calls,1,'readonly outbox must not replay');
context.state.readOnly=false;await vm.runInContext('request("/v1/messages",{text:"normal state"})',context);assert.equal(calls,2,'ordinary request flow unchanged');
const elements={'routing-note':{hidden:true,dataset:{tone:'error'},textContent:'stale account warning'},'account-reload':{hidden:false}};
context.$=id=>elements[id];
const routing=source.split('\n').find(line=>line.startsWith('function renderReadOnlyRouting('));assert.ok(routing);vm.runInContext(routing,context);
context.state.readOnly=true;vm.runInContext('renderReadOnlyRouting()',context);
assert.equal(elements['routing-note'].hidden,false);assert.match(elements['routing-note'].textContent,/chỉ đọc/);assert.equal(elements['routing-note'].dataset.tone,'normal');
assert.equal(elements['account-reload'].hidden,true);
context.state.readOnly=false;elements['routing-note'].textContent='ordinary notice';vm.runInContext('renderReadOnlyRouting()',context);assert.equal(elements['routing-note'].textContent,'ordinary notice');
console.log(JSON.stringify({status:'PASS',checks:7,scope:'Actual committed UI functions in Node VM, no browser/Core/provider'}));
