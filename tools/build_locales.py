"""Validate local catalogues and bundle them for the offline Go/Tauri frontend."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LANGUAGES = ('vi', 'en', 'zh-Hans', 'zh-Hant')
OUTPUT = ROOT / 'app/native/internal/web/assets/app/aurora/locales.js'


def bundle():
    resources = {lang: json.loads((ROOT / f'app/locales/{lang}.json').read_text('utf8')) for lang in LANGUAGES}
    baseline = resources['en']
    for lang, catalog in resources.items():
        assert catalog.keys() == baseline.keys(), f'{lang}: namespace mismatch'
        for namespace, messages in catalog.items():
            assert messages.keys() == baseline[namespace].keys(), f'{lang}/{namespace}: missing or extra keys'
            for key, value in messages.items():
                assert isinstance(value, str) and value.strip(), f'{lang}/{namespace}/{key}: empty message'
                placeholders = lambda text: sorted(re.findall(r'{{\s*([^}]+?)\s*}}', text))
                assert placeholders(value) == placeholders(baseline[namespace][key]), f'{lang}/{namespace}/{key}: placeholders differ'
    return '// Generated by python tools/build_locales.py. Edit app/locales/*.json.\nwindow.AURORA_LOCALES=' + json.dumps(resources, ensure_ascii=False, separators=(',', ':')) + ';\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = bundle()
    if args.check:
        assert OUTPUT.read_text('utf8') == result, 'Locale bundle is stale; run python tools/build_locales.py'
    else:
        OUTPUT.write_text(result, encoding='utf8', newline='\n')
    print('PASS: four catalogues, namespaces, placeholders and browser bundle')
